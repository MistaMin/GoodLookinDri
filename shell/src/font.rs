pub fn glyph(c: char) -> &'static [u8; 5] {
    let i = c as usize;
    if (32..=126).contains(&i) { &GLYPHS[i - 32] } else { &GLYPHS[(b'?' - 32) as usize] }
}

/// Width of `text` in font pixels (6 per glyph, minus the trailing gap).
pub fn width_cells(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 { 0 } else { n * (GLYPH_W + 1) - 1 }
}
